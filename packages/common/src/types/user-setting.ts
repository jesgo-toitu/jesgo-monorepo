/**
 * 利用者ごとの設定
 * 利用者（jesgo_user）1 人につき 1 つ持つ設定。施設全体の設定（システム設定）とは別物。
 */
export interface UserSetting {
  /**
   * 症例登録画面の保存確認ダイアログを表示しないか否か
   * - false: 表示する（既定）
   * - true: 表示しない（未保存の変更がある状態でタブを切り替えると、確認なしで保存する。
   *   ドキュメントを追加した直後、スキーマを変更した直後も同様）
   */
  hide_save_confirm: boolean;
}

/**
 * 利用者ごとの設定の既定値
 * 既存・新規の利用者とも、保存確認ダイアログは「表示する」
 */
export const DEFAULT_USER_SETTING: Readonly<UserSetting> = {
  hide_save_confirm: false,
};

/**
 * 保存確認の表示設定の名称・説明文（ユーザーメニューと利用者管理で同じ文面を使う）
 */
export const SaveConfirmSettingText = {
  /** 設定項目（チェックボックス）の名称 */
  LABEL: '症例登録画面でタブを切り替えるときに、保存確認を表示しない',
  /** 設定項目の説明文 */
  DESCRIPTION:
    'チェックを入れると、未保存の変更がある状態でタブを切り替えたときに、「保存します。よろしいですか？」の確認を表示せず、そのまま保存します。ドキュメントを追加した直後、スキーマを変更した直後も同様に、確認を表示せず保存します。入力エラーや保存失敗などの表示は、この設定にかかわらず表示されます。',
} as const;
